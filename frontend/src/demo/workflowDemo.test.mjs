import assert from 'node:assert/strict'
import {createDemoApps,takeDemoAction,resubmitDemo,assignedRole} from './workflowDemo.mjs'
let a=createDemoApps()[0]; const original=structuredClone(a)
assert.throws(()=>takeDemoAction(a,'DIRECTOR','approve','ok',1),/not pending/)
assert.throws(()=>takeDemoAction(a,'HOD','approve',' ',1),/comments/)
a=takeDemoAction(a,'HOD','approve','Reviewed',1)
assert.equal(assignedRole(a),'DEAN_FW')
assert.throws(()=>takeDemoAction(a,'DEAN_FW','approve','Reviewed',1),/changed/)
a=takeDemoAction(a,'DEAN_FW','return','Please clarify',a.version)
assert.equal(a.status,'Returned');assert.equal(assignedRole(a),null)
assert.throws(()=>resubmitDemo(a,'HOD','Correction',a.version),/Only/)
a=resubmitDemo(a,'FACULTY','Corrected self-appraisal',a.version)
assert.equal(a.revision,2);assert.equal(assignedRole(a),'HOD')
assert.deepEqual(a.revisions[0],original.revisions[0]);assert.equal(a.revisions[1].form.selfAppraisal,'Corrected self-appraisal')
for(const role of ['HOD','DEAN_FW','DIRECTOR']) a=takeDemoAction(a,role,'approve','Reviewed',a.version)
assert.equal(a.status,'Completed');assert.equal(assignedRole(a),null)
assert.throws(()=>takeDemoAction(a,'DIRECTOR','approve','Repeated',a.version),/not pending/)
assert.equal(original.history.length,1);assert.equal(a.history.length,7)
assert.deepEqual(createDemoApps().map(assignedRole),['HOD','DEAN_FW','DIRECTOR'])
console.log('PASS: full approval, return/resubmit, revision retention, invalid roles, empty comments, stale versions and repeat action protection.')
